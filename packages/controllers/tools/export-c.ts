// Writes the published CHOWK policy as dependency-free C, with recorded test cases whose
// expected outputs are exact IEEE-754 bit patterns from the TypeScript inference.
// npm run policy:c   (then compile exports/c/check.c with any C99 compiler)
import { readFileSync, writeFileSync } from "node:fs";
import { makeScenario } from "@chowk/scenarios";
import { corridor, createSim } from "@chowk/sim";
import { createController, decodePolicy, type PolicyWeights } from "../src";
import { Inference } from "../src/policy/inference";
import { buildObservation, layoutFor } from "../src/policy/observation";
import { POLICY_DIMENSIONS, POLICY_PARAMETER_COUNT } from "../src/policy/weights";

const policy = JSON.parse(
  readFileSync("apps/web/public/policies/chowk.json", "utf8"),
) as PolicyWeights;
const vector = decodePolicy(policy);
const floatLiteral = (value: number) => {
  if (Object.is(value, -0)) return "-0.0f";
  const text = value.toPrecision(9);
  return `${text.includes("e") || text.includes(".") ? text : `${text}.0`}f`;
};
// Every float32 printed with 9 significant digits parses back to the same float32.
for (let index = 0; index < vector.length; index++) {
  const back = Math.fround(Number(floatLiteral(vector[index]).replace(/f$/, "")));
  if (!Object.is(back, vector[index])) throw new Error(`Weight ${index} does not round-trip`);
}
const lines: string[] = [];
for (let index = 0; index < vector.length; index += 6)
  lines.push(`  ${Array.from(vector.subarray(index, index + 6), floatLiteral).join(", ")},`);

const [inputs, first, second, outputs] = POLICY_DIMENSIONS;
const header = `/* CHOWK policy, generation ${policy.meta.generation}, exported from apps/web/public/policies/chowk.json.
 * Dependency-free C99: addition, multiplication and comparison in double precision, in the
 * same order as packages/controllers/src/policy/inference.ts, so outputs match bit for bit.
 * Generated by packages/controllers/tools/export-c.ts; do not edit. */
#ifndef CHOWK_POLICY_H
#define CHOWK_POLICY_H

#define CHOWK_INPUTS ${inputs}
#define CHOWK_OUTPUTS ${outputs}
#define CHOWK_PARAMETERS ${POLICY_PARAMETER_COUNT}

static const float CHOWK_WEIGHTS[${vector.length}] = {
${lines.join("\n")}
};

/* Residual scale applied to the max-pressure prior. */
#define CHOWK_BETA ((double)CHOWK_WEIGHTS[${POLICY_PARAMETER_COUNT}])

static void chowk_layer(const float *w, const double *in, int inputs, int outputs, int relu, double *out) {
  const float *bias = w + inputs * outputs;
  for (int row = 0; row < outputs; row++) {
    double value = (double)bias[row];
    const float *weights = w + row * inputs;
    for (int col = 0; col < inputs; col++) value += (double)weights[col] * in[col];
    out[row] = relu && value < 0.0 ? 0.0 : value;
  }
}

/* observation: 50 values built as in observation.ts; output: 4 learned scores by relative direction. */
static void chowk_policy(const double observation[CHOWK_INPUTS], double output[CHOWK_OUTPUTS]) {
  double hidden1[${first}], hidden2[${second}];
  chowk_layer(CHOWK_WEIGHTS, observation, ${inputs}, ${first}, 1, hidden1);
  chowk_layer(CHOWK_WEIGHTS + ${inputs * first + first}, hidden1, ${first}, ${second}, 1, hidden2);
  chowk_layer(CHOWK_WEIGHTS + ${inputs * first + first + first * second + second}, hidden2, ${second}, ${outputs}, 0, output);
}

#endif
`;
writeFileSync("exports/c/chowk_policy.h", header);

// Test cases: real observations from a validation-seed run, plus random inputs in range.
const cases: Float64Array[] = [];
const scenario = makeScenario("morning-peak", { duration: 900 });
const sim = createSim({ network: corridor, scenario, seed: 500_011 });
for (let step = 0; step < 30; step++) {
  sim.step(120);
  for (const { id } of corridor.junctions) {
    const sense = sim.sense(id);
    const observation = new Float64Array(inputs);
    buildObservation(
      layoutFor(corridor, id),
      sense,
      {
        time: sim.time,
        approaches: sense.approaches.map(() => ({ releasing: false, elapsed: 0 })),
      },
      observation,
      false,
      false,
    );
    cases.push(observation);
  }
}
let state = 20_261_113;
for (let index = 0; index < 100; index++) {
  const observation = new Float64Array(inputs);
  for (let col = 0; col < inputs; col++) {
    state = (Math.imul(state, 1_103_515_245) + 12_345) >>> 0;
    observation[col] = (state / 0x1_0000_0000) * 1.5;
  }
  cases.push(observation);
}
const inference = new Inference(vector);
const output = new Float64Array(outputs);
const bits = new DataView(new ArrayBuffer(8));
const hex = (value: number) => {
  bits.setFloat64(0, value);
  return `0x${bits.getBigUint64(0).toString(16).padStart(16, "0")}ULL`;
};
const caseLines = cases.map((observation) => {
  inference.evaluate(observation, output);
  return `  {{${Array.from(observation, (value) => (Number.isInteger(value) ? `${value}.0` : String(value))).join(", ")}}, {${Array.from(output, hex).join(", ")}}},`;
});
// Guard the controller path too: the ResidualPolicy must agree with Inference.
createController("chowk", { policy });
writeFileSync(
  "exports/c/chowk_cases.h",
  `/* ${cases.length} observations with expected outputs as IEEE-754 bit patterns. Generated; do not edit. */
#include <stdint.h>
static const struct { double observation[${inputs}]; uint64_t expected[${outputs}]; } CHOWK_CASES[] = {
${caseLines.join("\n")}
};
`,
);
process.stdout.write(`Wrote exports/c/chowk_policy.h and ${cases.length} cases\n`);
